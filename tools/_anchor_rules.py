# -*- coding: utf-8 -*-
r"""收窄「视觉设定缺失项」的判据——只比**外观名词**，不比剧情动作。

## 上一版的误报（30 条里大半是假的）

它把「本集状态」整段拿去和实体描述比，于是报出：

    [主管] 本集状态里有这几项在实体描述中找不到：走过水渍地面、不抬头、
           对沈九的质问不回应

**这些是剧情动作，本来就不该进人物描述。** 人物描述写的是**相貌与妆造**；
"不抬头""递给沈九"属于镜头里的表演，归分镜管。

同理「SC002 由沈九从推把上取下看过又挂回」——那是动作，不是外观。

## 正确的判据

只比 **「识别锚点」与「连续性锁」** 里**像外观**的项，而且要满足：
  · 是名词性的（含「色 / 材质 / 带 / 牌 / 笔 / 帽 / 镜 / 表 / 墙 / 门 / 地 / 灯
    / 大小 / 长 / 高 / 形状 / 刻字 / 磨损 / 边缘」这类外观词）
  · 长度 ≥3
  · **不含明显动作词**（说/问/答/走/抬头/递给/抽出/塞进/取下/看/回/抬/伸/攥）

并且**只对这种项**报"缺失"。宁可少报，不要假报——
**假报会让这个审查器失去信用，最后没人看它**（今天已经在 lint 上踩过这个坑）。
"""
import re

# 外观词：出现这些，才认为该项在描述"长什么样"
LOOKS = ("色", "材质", "带", "牌", "笔", "帽", "镜", "表", "墙", "门", "地",
         "灯", "大小", "长度", "高度", "形状", "刻字", "磨损", "边缘", "表面",
         "纹", "孔", "层", "款", "式", "质",
         # 刻字/刻痕：库里可能写成"刻有炉位编号"或"带刻字"，
         # 所以判据要认"刻"这个字根，不要认死"刻字"这个词。
         # 踩过：黄铜签牌描述已写「表面刻有炉位编号（深色刻痕）」，
         # 规则却因为找不到"刻字"而报缺失。
         "刻")
# 动作词：出现这些，说明该项在描述"做什么"，不归人物描述管
# 力道类：**拍不出来**，不是外观项。踩过：盛伯渊「右手力气反常地大」
# 被报成"像外观但描述里找不到"——这种描述本来就无法进画面。
NOT_VISIBLE = ("力气", "力量", "力大", "力气大", "体温", "冰凉", "温度感",
               "心跳", "呼吸", "气味", "声音", "语气", "性格", "心理")

ACTIONS = ("说", "问", "答", "走", "抬头", "递给", "抽出", "塞进", "取下",
           "看过", "回", "抬", "伸", "攥", "盯着", "低", "挪", "掐", "擦",
           "戴上", "按下", "压", "推", "拉", "进", "出", "在", "由", "被",
           "未", "仍", "会", "要", "让", "使", "能", "可", "从", "向", "对")


def is_looks_like(item):
    """这一项在描述外观吗？（只报外观项缺失，才不误报）"""
    if len(item) < 3:
        return False
    if any(v in item for v in NOT_VISIBLE):
        return False
    if any(a in item for a in ACTIONS):
        return False
    return any(k in item for k in LOOKS)


# 同义词映射：**期望写法 -> 描述里可能的实际写法**
#
# ⚠️ 为什么需要：逐字比对会把「同义表达」判成缺失，今天已踩两次——
#   · 期望「带刻字」，描述写「表面刻有炉位编号（深色刻痕）」→ 逐字命中仅 33%
#   · 同源的还有跨集连续性那次：「被人扫过」vs 正文「有人去扫过」
# 中文同一件事有多种说法，**比对语义而不是逐字**，否则误报会淹掉真问题。
SYNONYMS = {
    "带刻字": ("刻有", "刻痕", "刻着", "阴刻", "刻字", "铭文"),
    "刻字": ("刻有", "刻痕", "刻着", "阴刻", "铭文"),
    "掌心大小": ("掌心", "掌心里", "巴掌大", "约3厘米", "小巧"),
    "大小": ("尺寸", "厘米", "长约", "宽约", "高约", "小巧"),
    "带编号": ("编号", "号码", "序号", "工号"),
    "无字": ("纯色空白", "无印刷", "无标识", "表面平整", "无任何字符"),
    "待机红灯": ("待机", "红色指示灯", "红灯", "指示灯"),
    "条子": ("便签", "纸条", "纸质便签", "打印"),
    "墙上挂金属外壳的红字数码倒计时牌": ("倒计时牌", "电子倒计时牌", "数码屏",
                                        "红字"),
    "红字数码倒计时牌": ("倒计时牌", "电子倒计时牌", "数码屏", "红字"),
    "显示距入炉的剩余时间": ("倒计时", "剩余时间", "跳秒"),
}


def _realized(item, desc):
    """这一项（或其同义写法）在描述里出现了吗？返回命中的写法或 None。

    ## 两个踩过的坑

    1. **锚点被逗号切成长段**：视觉设定写「墙上挂金属外壳的**红字数码倒计时牌**
       （显示距入炉的剩余时间，能跳秒）」，按逗号切出来的一项是一长串。
       早先用**全等**查同义词表，键对不上，表形同虚设。
       ⇒ 现在用**子串包含**：只要某项的同义词出现在这一项里，就算命中。
    2. **Markdown 标记**：同一句里有 `**加粗**`，查表前必须清掉。
    """
    key = item.replace("**", "").replace("__", "").replace("`", "").strip()
    if not key:
        return None
    # ① 子串包含：同义词只要出现在这一项里就算命中
    for expect, syns in SYNONYMS.items():
        if expect in key or key in expect:
            for syn in syns:
                if syn in (desc or ""):
                    return syn
    # ② 整串直接命中描述（长项常含括号补充，描述里可能原样出现）
    if len(key) >= 4 and key in (desc or ""):
        return key
    return None


def missing_looks(anchor_text, desc):
    """从锚点文本里找出**像外观、但描述里没有**的项。

    判定**同义词优先**，逐字命中率只用于报告可读。
    """
    out = []
    for part in re.split(r"[；;，,、]", anchor_text or ""):
        p = part.strip().strip("（）()").strip()
        if not is_looks_like(p):
            continue
        if _realized(p, desc):
            continue
        chars = [c for c in p if "\u4e00" <= c <= "\u9fff"]
        if not chars:
            continue
        hit = sum(1 for c in chars if c in (desc or ""))
        ratio = hit / len(chars)
        # 阈值 0.6：中文同义改写的逐字命中常在 0.5 上下，
        # 卡 0.5 会把"刻有编号"这类正当改写判成缺失。
        if ratio < 0.6:
            out.append((p, round(ratio, 2)))
    return out
