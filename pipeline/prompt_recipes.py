def _hit(label, table):
    """把分镜里的短标签对到表上；对不上返回 None（**不编造**）。"""
    s = (label or "").strip()
    if not s:
        return None
    if s in table:
        return table[s]
    if s in _ALIASES and _ALIASES[s] in table:
        return table[_ALIASES[s]]
    for k, v in table.items():
        if k and k in s:                       # "特写镜头" ⊃ "特写"
            return v
    return None


def shot_size_clause(size):
    """景别的配方句（过滤版）。对不上返回 ""——**不猜**。"""
    return _hit(size, SHOT_SIZE_CLAUSE) or ""


def camera_key(move):
    """运镜字段 → 表内键；**只认短标签与其别名**，认不出返回 None。

    为什么不用"长度短就算标签"这种模糊判断：
    分镜里的 `camera_emotion` 已经写好了"陪伴式平移""爆发式急推"这类**富描述**，
    模糊判断会把它们也算成标签，然后套上一句可能**与镜头意图矛盾**的配方
    （实测：S05"爆发式急推至眼部特写"被套上"由全景渐入中景"）。
    """
    s = (move or "").strip()
    if not s:
        return None
    if s in CAMERA_CLAUSE:
        return s
    if s in _CAM_ALIASES:
        return _CAM_ALIASES[s]
    return None


def camera_clause(move):
    """运镜的配方句（过滤版）。不是短标签就返回 ""（**不猜、不重复**）。"""
    k = camera_key(move)
    return CAMERA_CLAUSE[k] if k else ""
