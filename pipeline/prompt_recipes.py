r"""景别 / 运镜的**提示词配方句**——出处：外部《小蕾知识库分享版》PDF。

## 这份表解决什么问题

我们的分镜字段是**短标签**：景别写"特写"、运镜写"推"。模型收到的就是这两个字。
而外部这份库把每个景别/运镜都写成**一整句技术描述**
（"超清微距特写，皮肤纹理与物体质感增强"），
让模型知道**要往哪个方向使劲**。

## ⚠️ 为什么要"过滤"才注入（不是照抄）

那份库的句子是**写给 3D CG 国漫**的，而且句子里**混了运动指令**：

- 「全景 → **智能全景跟随**，主体与环境光影互动清晰…」
  → "跟随"是**运动**。我们另有一行【运镜】和我们自己的**静止锁**；
    照抄进去会出现"固定机位"和"全景跟随"**互相打架**（S06/S07/S11 就是固定镜）。
- 「特写 → …加入**轻微镜头颤动**模拟真实拍摄」
  → 同理，和"固定"冲突。
- 「推镜头 → …**每秒钟移动5-10厘米**」
  → 速度我们有自己的字段（`movement_speed`），照抄会写两遍速度。

所以本模块分两层：
- `SHOT_SIZE_VERBATIM` / `CAMERA_VERBATIM`：**原文照录**，供查证（谁都能对回 PDF）
- `shot_size_clause()` / `camera_clause()`：**过滤后**才进提示词
  —— 景别只取"光学/质感/氛围"部分，**剥掉运动**；运镜剥掉速度数字。

## 另一条**没采纳**的（有冲突，需实测）

那份库大量使用 **"0-3秒…3-5秒…5-8秒"精确时间码**推进动作；
而我们知识库《拾音人范本与工艺规范》§一.2 明确写**"不写精确时间码"**
（理由：模型对精确时间支持不稳定）。
**两条不能都信，尚未实测——所以这里一律不用时间码。**
"""
